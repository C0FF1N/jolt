// Generates docs/performance-benchmarks.md from the raw JSON in bench/results.
// Nothing here is hand-entered: every number comes from a results file.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const resultsDir = path.join(here, "../results");
const out = path.join(here, "../../docs/performance-benchmarks.md");

const latest = (re) => {
  const f = readdirSync(resultsDir).filter((n) => re.test(n)).sort().at(-1);
  if (!f) return null;
  return { file: f, data: JSON.parse(readFileSync(path.join(resultsDir, f), "utf8")) };
};

const real = latest(/^real-chrome-\d+\.json$/);
const mockBase = latest(/^baseline-legacy-mock-\d+\.json$/);
const mockLegacy = latest(/^turbo-legacy-mock-\d+\.json$/);
const mockBundle = latest(/^turbo-bundle-mock-\d+\.json$/);

const f1 = (n) => (n === undefined || n === null ? "–" : n.toFixed(1));
const pct = (a, b) => (a && b !== undefined ? `${(((b - a) / a) * 100).toFixed(0)}%` : "–");
const lines = [];
const L = (s = "") => lines.push(s);

L("# Performance benchmarks");
L();
L("> Generated by `bench/src/report.mjs` from the raw JSON files in `bench/results/`. Do not edit by hand;");
L("> re-run the benchmarks and the report script instead (see *Reproduce*).");
L(">");
L("> **Naming:** these runs were recorded while the optimized server was still called \"turbo\". In every table,");
L("> **turbo** is Jolt's server (`apps/server`) and **baseline** is the unmodified upstream Browser MCP server (`baseline/`).");
L();

if (real) {
  const e = real.data.env;
  const B = real.data.targets.baseline.scenarios;
  const T = real.data.targets.turbo.scenarios;
  L("## 1. Real browser A/B (headless Chromium, same extension for both servers)");
  L();
  L(`Source: \`${real.file}\`. Chromium ${e.chromium}, Node ${e.node}, ${e.os}, ${e.cpu} (${e.cores} cores, ${e.totalMemGb} GB). Run: ${e.date}.`);
  L(`${real.data.iterations} measured iterations per scenario after ${real.data.warmup} warm-up iterations. **baseline** = unmodified upstream server, **turbo** = this repo's server.`);
  L("Both talk to the *same* new extension (`apps/extension`) on the same fixture pages, so differences come from the server only.");
  L();
  L("| Scenario | baseline median / p95 (ms) | turbo median / p95 (ms) | Δ median | baseline → turbo response bytes (median) | tool calls |");
  L("|---|---|---|---|---|---|");
  for (const name of Object.keys(B)) {
    const b = B[name];
    const t = T[name];
    L(`| ${name} | ${f1(b.latency_ms.median)} / ${f1(b.latency_ms.p95)} | ${f1(t.latency_ms.median)} / ${f1(t.latency_ms.p95)} | ${pct(b.latency_ms.median, t.latency_ms.median)} | ${b.response_bytes.median} → ${t.response_bytes.median} | ${b.tool_calls_per_iter} → ${t.tool_calls_per_iter} |`);
  }
  L();
  L("### New capabilities, compared with the equivalent baseline workflow");
  L();
  L("| Turbo-only scenario | compared with baseline | turbo median (ms) | baseline median (ms) | Δ median | turbo → baseline bytes | turbo → baseline tool calls |");
  L("|---|---|---|---|---|---|---|");
  const pairs = [
    ["click_snapshot_none", "click"],
    ["sequence_10_snapshot_none", "sequence_10_standard_tools"],
    ["batch_10", "sequence_10_standard_tools"],
  ];
  for (const [tn, bn] of pairs) {
    const t = T[tn];
    const b = B[bn];
    if (!t || !b) continue;
    L(`| ${tn} | ${bn} | ${f1(t.latency_ms.median)} | ${f1(b.latency_ms.median)} | ${pct(b.latency_ms.median, t.latency_ms.median)} | ${t.response_bytes.median} vs ${b.response_bytes.median} (${pct(b.response_bytes.median, t.response_bytes.median)}) | ${t.tool_calls_per_iter} vs ${b.tool_calls_per_iter} |`);
  }
  L();
  L("### Cold start (fresh server process + fresh tab connection, 5 runs)");
  L();
  L("| Server | connect median / p95 (ms) | first snapshot median / p95 (ms) |");
  L("|---|---|---|");
  for (const n of ["baseline", "turbo"]) {
    const c = real.data.targets[n].cold;
    L(`| ${n} | ${f1(c.connect_ms.median)} / ${f1(c.connect_ms.p95)} | ${f1(c.first_snapshot_ms.median)} / ${f1(c.first_snapshot_ms.p95)} |`);
  }
  L();
  const anyFail = Object.entries({ baseline: B, turbo: T }).flatMap(([n, s]) =>
    Object.entries(s).filter(([, v]) => v.failure_rate > 0).map(([k, v]) => `${n}/${k}: ${(v.failure_rate * 100).toFixed(0)}%`));
  L(`Failure rate: ${anyFail.length ? anyFail.join(", ") : "0% in every scenario (no failed tool calls, no timeouts)"}.`);
  L();
}

if (mockBase && mockLegacy && mockBundle) {
  const B = mockBase.data.scenarios;
  const Tl = mockLegacy.data.scenarios;
  const Tb = mockBundle.data.scenarios;
  L("## 2. Server/protocol overhead with a mock extension (no browser)");
  L();
  L(`Sources: \`${mockBase.file}\`, \`${mockLegacy.file}\`, \`${mockBundle.file}\`. The mock extension answers instantly (simulated extension time = 0), so these numbers isolate the *server and WebSocket protocol* cost and count **WebSocket round trips per iteration**.`);
  L("*turbo (legacy)* = extension that sends no handshake (like the Web Store build); *turbo (bundle)* = extension advertising `snapshotBundle` (like the new extension).");
  L();
  L("| Scenario | WS round trips: baseline / turbo legacy / turbo bundle | median ms: baseline / legacy / bundle | response bytes (median) baseline → turbo |");
  L("|---|---|---|---|");
  for (const name of Object.keys(B)) {
    const rt = (s) => (s[name]?.ws_round_trips_per_iter ?? "–");
    L(`| ${name} | ${rt(B)} / ${rt(Tl)} / ${rt(Tb)} | ${f1(B[name].latency_ms.median)} / ${f1(Tl[name]?.latency_ms.median)} / ${f1(Tb[name]?.latency_ms.median)} | ${B[name].response_bytes?.median ?? "–"} → ${Tb[name]?.response_bytes?.median ?? "–"} |`);
  }
  for (const name of ["click_snapshot_none", "batch_10"]) {
    if (Tb[name]) {
      L(`| ${name} (turbo only) | – / ${Tl[name]?.ws_round_trips_per_iter} / ${Tb[name].ws_round_trips_per_iter} | – / ${f1(Tl[name]?.latency_ms.median)} / ${f1(Tb[name].latency_ms.median)} | – → ${Tb[name].response_bytes?.median} |`);
    }
  }
  L();
}

L("## Methodology");
L();
L("- **Harness:** `bench/src/run.mjs` (mock extension) and `bench/src/real-bench.mjs` (real Chromium). Both drive the built server over MCP stdio exactly like a client would, and time each `tools/call`.");
L("- **Statistics:** median and p95 (nearest-rank) of per-iteration wall time; warm-up iterations discarded; cold start measured separately with fresh processes.");
L("- **Setup is untimed:** page loads and ref lookups used to prepare a scenario are outside the measured region.");
L("- **Fairness:** same machine, same Chromium, same extension build, same fixture pages, same iteration counts for baseline and turbo; each server runs in its own process on its own loopback port.");
L("- **Round trips** are counted by the mock extension (messages received per iteration).");
L();
L("## Limitations (read before quoting any number)");
L();
L("- Single machine, single run set, not isolated from other processes; no confidence intervals. Differences under ~10% are within run-to-run noise.");
L("- Repeated runs of the same code differed by up to about ±10% for individual standard-tool scenarios (e.g. `navigate` read 23.5, 22.8, 23.2 and 25.4 ms across four runs). Do not read a difference of that size in one scenario as an improvement or a regression.");
L("- The `status` scenario calls `browser_get_console_logs`; its response bytes depend on whatever console output had accumulated in the tab, not on the server, so compare its latency only.");
L("- Fixtures are small local pages served from loopback. Real sites add network and render time, which dominate and are identical for both servers; relative gains from fewer round trips shrink as per-action browser time grows.");
L("- The Chromium here is Playwright's headless build, not branded Chrome, and the extension is this repo's reimplementation. **The original Web Store extension was not benchmarked** (loading it needs a manual Connect click in a profile where it is installed).");
L("- The mock-extension numbers use a zero-latency extension and therefore exaggerate protocol overhead relative to real use; they are valid for round-trip counts, not as user-visible latency.");
L("- Windows timer granularity (~15.6 ms for `setTimeout(1)`) makes a non-zero *simulated* extension delay unreliable; headline mock runs use 0 ms. `baseline-mock-rtt1-timer-quantized.json` is kept only as a documented example of this artefact.");
L("- CPU and memory of the server process were not measured reliably in the real-browser runs (the mock runner records RSS only as a rough point sample); no claim is made about CPU or memory improvement.");
L("- AI model latency and network conditions are out of scope; only tool execution time, payload bytes and call counts are measured.");
L();
L("## Reproduce");
L();
L("```bash");
L("pnpm install && pnpm -r build");
L("cd bench");
L("node src/run.mjs --target=baseline --label=legacy --rtt=0 --iterations=40");
L("node src/run.mjs --target=turbo --label=legacy --rtt=0 --iterations=40");
L("node src/run.mjs --target=turbo --label=bundle --caps=snapshotBundle --rtt=0 --iterations=40");
L("node src/real-bench.mjs --iterations=30 --warmup=5 --cold=5   # needs a Playwright Chromium (JOLT_BENCH_CHROME to override)");
L("node src/report.mjs");
L("```");

writeFileSync(out, lines.join("\n") + "\n");
console.log("wrote", out);
